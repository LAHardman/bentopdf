#!/usr/bin/env node
/**
 * Makes the generated iOS project buildable on a Mac-less CI runner and
 * registers the app as a handler for PDFs and Office documents.
 *
 * Three things Capacitor's template leaves out, all of which have to exist
 * before `xcodebuild` will archive on a machine nobody has opened Xcode on:
 *
 *   1. Document types. The iOS counterpart of the Android intent filters -
 *      without CFBundleDocumentTypes the app never shows up in the Files app
 *      or in another app's share sheet.
 *   2. A *shared* scheme. Xcode writes schemes into xcuserdata the first time
 *      a human opens the project, so a fresh checkout has none and
 *      `xcodebuild -scheme App` fails outright.
 *   3. ExportOptions.plist, which `xcodebuild -exportArchive` requires.
 *
 * None of it is expressible through capacitor.config.ts, and `ios/` is build
 * output regenerated by `cap add`, so this runs as part of native:init and
 * native:sync - same arrangement as scripts/native-patch-android.mjs.
 *
 * Idempotent: an already patched project is left alone.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iosDir = path.join(root, 'ios/App');
const plistPath = path.join(iosDir, 'App/Info.plist');
const pbxprojPath = path.join(iosDir, 'App.xcodeproj/project.pbxproj');
const schemeDir = path.join(iosDir, 'App.xcodeproj/xcshareddata/xcschemes');
const schemePath = path.join(schemeDir, 'App.xcscheme');
const exportOptionsPath = path.join(iosDir, 'ExportOptions.plist');

const MARKER = 'BentoPDF document types';

// native:sync runs this unconditionally, and plenty of checkouts only ever
// generate the Android project. Nothing to patch is not an error.
if (!fs.existsSync(plistPath)) {
  console.log('[native-patch] No iOS project - skipping.');
  process.exit(0);
}

// ------------------------------------------------------------ document types

/**
 * Grouped the way the Files app presents them, because each group becomes one
 * row in "Open with". LSHandlerRank Alternate keeps us out of the way of the
 * system PDF viewer while still offering BentoPDF as a choice.
 */
const DOCUMENT_TYPES = [
  { name: 'PDF Document', utis: ['com.adobe.pdf'] },
  {
    name: 'Word Document',
    utis: [
      'com.microsoft.word.doc',
      'org.openxmlformats.wordprocessingml.document',
      'org.oasis-open.opendocument.text',
      'public.rtf',
    ],
  },
  {
    name: 'Spreadsheet',
    utis: [
      'com.microsoft.excel.xls',
      'org.openxmlformats.spreadsheetml.sheet',
      'org.oasis-open.opendocument.spreadsheet',
    ],
  },
  {
    name: 'Presentation',
    utis: [
      'com.microsoft.powerpoint.ppt',
      'org.openxmlformats.presentationml.presentation',
      'org.oasis-open.opendocument.presentation',
    ],
  },
];

const documentTypesXml = () => {
  const entries = DOCUMENT_TYPES.map(
    ({ name, utis }) => `		<dict>
			<key>CFBundleTypeName</key>
			<string>${name}</string>
			<key>CFBundleTypeRole</key>
			<string>Editor</string>
			<key>LSHandlerRank</key>
			<string>Alternate</string>
			<key>LSItemContentTypes</key>
			<array>
${utis.map((uti) => `				<string>${uti}</string>`).join('\n')}
			</array>
		</dict>`
  ).join('\n');

  return `	<!-- ${MARKER} (scripts/native-patch-ios.mjs) -->
	<key>CFBundleDocumentTypes</key>
	<array>
${entries}
	</array>
	<!-- Show the app's documents in the Files app and let it edit them in place. -->
	<key>UIFileSharingEnabled</key>
	<true/>
	<key>LSSupportsOpeningDocumentsInPlace</key>
	<true/>
	<!-- BentoPDF's PDF encryption is the standard algorithm published in the PDF
	     spec, which is exempt. Declaring it here stops App Store Connect asking
	     on every single upload. -->
	<key>ITSAppUsesNonExemptEncryption</key>
	<false/>
`;
};

const plist = fs.readFileSync(plistPath, 'utf8');

if (plist.includes(MARKER)) {
  console.log('[native-patch] Info.plist already registers documents.');
} else {
  const anchor = '</dict>\n</plist>';
  if (!plist.includes(anchor)) {
    console.error(
      '[native-patch] Could not find the end of Info.plist.\n' +
        '               Capacitor may have changed its template - patch it by hand.'
    );
    process.exit(1);
  }

  fs.writeFileSync(
    plistPath,
    plist.replace(anchor, `${documentTypesXml()}</dict>\n</plist>`)
  );
  const count = DOCUMENT_TYPES.reduce((n, t) => n + t.utis.length, 0);
  console.log(
    `[native-patch] Registered ${count} document types across ${DOCUMENT_TYPES.length} groups.`
  );
}

// ------------------------------------------------------------- shared scheme

/**
 * The scheme has to name the target by its pbxproj UUID. Reading it back
 * rather than hardcoding means a Capacitor template change surfaces as a clear
 * error here instead of an inscrutable xcodebuild failure later.
 */
const appTargetId = () => {
  const pbxproj = fs.readFileSync(pbxprojPath, 'utf8');
  const match = pbxproj.match(
    /([0-9A-F]{24}) \/\* App \*\/ = \{\s*\n\s*isa = PBXNativeTarget;/
  );
  if (!match) {
    console.error(
      '[native-patch] Could not find the App target in project.pbxproj.'
    );
    process.exit(1);
  }
  return match[1];
};

if (fs.existsSync(schemePath)) {
  console.log('[native-patch] Shared scheme already present.');
} else {
  const targetId = appTargetId();
  const buildable = `      <BuildableReference
         BuildableIdentifier = "primary"
         BlueprintIdentifier = "${targetId}"
         BuildableName = "App.app"
         BlueprintName = "App"
         ReferencedContainer = "container:App.xcodeproj">
      </BuildableReference>`;

  fs.mkdirSync(schemeDir, { recursive: true });
  fs.writeFileSync(
    schemePath,
    `<?xml version="1.0" encoding="UTF-8"?>
<Scheme
   LastUpgradeVersion = "1500"
   version = "1.3">
   <BuildAction
      parallelizeBuildables = "YES"
      buildImplicitDependencies = "YES">
      <BuildActionEntries>
         <BuildActionEntry
            buildForTesting = "YES"
            buildForRunning = "YES"
            buildForProfiling = "YES"
            buildForArchiving = "YES"
            buildForAnalyzing = "YES">
${buildable}
         </BuildActionEntry>
      </BuildActionEntries>
   </BuildAction>
   <TestAction
      buildConfiguration = "Debug"
      selectedDebuggerIdentifier = "Xcode.DebuggerFoundation.Debugger.LLDB"
      selectedLauncherIdentifier = "Xcode.DebuggerFoundation.Launcher.LLDB"
      shouldUseLaunchSchemeArgsEnv = "YES">
      <Testables>
      </Testables>
   </TestAction>
   <LaunchAction
      buildConfiguration = "Debug"
      selectedDebuggerIdentifier = "Xcode.DebuggerFoundation.Debugger.LLDB"
      selectedLauncherIdentifier = "Xcode.DebuggerFoundation.Launcher.LLDB"
      launchStyle = "0"
      useCustomWorkingDirectory = "NO"
      ignoresPersistentStateOnLaunch = "NO"
      debugDocumentVersioning = "YES"
      debugServiceExtension = "internal"
      allowLocationSimulation = "YES">
      <BuildableProductRunnable
         runnableDebuggingMode = "0">
${buildable}
      </BuildableProductRunnable>
   </LaunchAction>
   <ProfileAction
      buildConfiguration = "Release"
      shouldUseLaunchSchemeArgsEnv = "YES"
      savedToolIdentifier = ""
      useCustomWorkingDirectory = "NO"
      debugDocumentVersioning = "YES">
      <BuildableProductRunnable
         runnableDebuggingMode = "0">
${buildable}
      </BuildableProductRunnable>
   </ProfileAction>
   <AnalyzeAction
      buildConfiguration = "Debug">
   </AnalyzeAction>
   <ArchiveAction
      buildConfiguration = "Release"
      revealArchiveInOrganizer = "YES">
   </ArchiveAction>
</Scheme>
`
  );
  console.log(`[native-patch] Wrote a shared App scheme (target ${targetId}).`);
}

// ------------------------------------------------------------ export options

/**
 * `xcodebuild -exportArchive` refuses to run without this. app-store-connect
 * is the method TestFlight wants; uploading is a separate step so a failed
 * upload does not mean rebuilding.
 */
if (fs.existsSync(exportOptionsPath)) {
  console.log('[native-patch] ExportOptions.plist already present.');
} else {
  fs.writeFileSync(
    exportOptionsPath,
    `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>method</key>
	<string>app-store-connect</string>
	<key>destination</key>
	<string>export</string>
	<key>signingStyle</key>
	<string>automatic</string>
	<key>uploadSymbols</key>
	<true/>
	<key>manageAppVersionAndBuildNumber</key>
	<false/>
</dict>
</plist>
`
  );
  console.log('[native-patch] Wrote ExportOptions.plist.');
}
